def tab_family_a() -> None:
    fa = pd.read_csv("tables/table_p5_family_a.csv")
    guard = pd.read_csv("tables/table_p5_perclass_guard.csv")
    p5 = pd.read_csv("results/p5_factor_ablation_full.csv")
    lines = [
        "% AUTO-GENERATED by src/paper/w5_result_tables.py",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Family~A (pre-registered, 9 Holm-corrected tests): soft retention vs.\\ hard",
        " deletion, Tail-F1, final frozen protocol. Macro $\\Delta$ is the paired macro-F1 mean",
        " difference; worst class is the largest per-class F1 regression (guard $\\le$0.05).",
        " Verdict: \\textbf{robust} (3/3 datasets).}",
        "\\label{tab:family-a}", "\\small",
        "\\begin{tabular}{llccccc}", "\\toprule",
        "Dataset & Rate & $\\Delta$ Tail-F1 & Holm $p$ & $d_z$ & 95\\% CI & Macro $\\Delta$ / worst class \\\\",
        "\\midrule",
    ]
    prev = None
    for ds in DS_ORDER:
        for _, r in fa[fa.dataset == ds].sort_values("tail_flip_rate").iterrows():
            rate = r.tail_flip_rate
            soft = p5[(p5.dataset == ds) & (p5.cell == "4_graph_cdm_soft") & (np.isclose(p5.tail_flip_rate, rate))]
            hard = p5[(p5.dataset == ds) & (p5.cell == "3_graph_cdm_hard") & (np.isclose(p5.tail_flip_rate, rate))]
            macro_d = (soft.sort_values("seed").macro_f1.to_numpy() - hard.sort_values("seed").macro_f1.to_numpy()).mean()
            g = guard[(guard.dataset == ds) & (np.isclose(guard.tail_flip_rate, rate))]
            worst = float(g.worst_mean_delta.iloc[0])
            assert bool(g.passed.iloc[0]), f"guard failed {ds}@{rate}"
            d = DS_LABEL[ds] if ds != prev else ""
            if ds != prev and prev is not None:
                lines.append("\\midrule")
            prev = ds
            lines.append(
                f"{d} & {rate:.1f} & {r.mean_delta:+.3f} & {_p(r.p_holm_greater)} & {r.cohens_dz:.2f} & "
                f"{_ci(r.bootstrap_ci95_low, r.bootstrap_ci95_high)} & {macro_d:+.3f} / {worst:+.3f} \\\\"
            )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    _write("tab_family_a.tex", "\n".join(lines) + "\n",
           ["tables/table_p5_family_a.csv", "tables/table_p5_perclass_guard.csv",
            "results/p5_factor_ablation_full.csv"])


