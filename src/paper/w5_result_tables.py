"""W5-1: generate final-manuscript LaTeX tables from frozen artifacts.

Discipline: inferential statistics (Holm p, dz, bootstrap CI) are READ from
frozen CSV/JSON, never recomputed.  Only deterministic aggregate means/stds
are computed here (main table).  Emits fragments to paper/springer/tables_w5/
plus a traceability manifest (table -> source artifacts) for the audit gate.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

OUT = Path("paper/springer/tables_w5")
DS_LABEL = {"cesnet_tls_year22": "CESNET", "cicids2017": "CICIDS", "unsw_nb15": "UNSW"}
DS_ORDER = ["cicids2017", "cesnet_tls_year22", "unsw_nb15"]
MANIFEST: dict[str, list[str]] = {}


def _p(v: float) -> str:
    return "$<$0.001" if v < 0.001 else f"{v:.3f}"


def _ci(lo: float, hi: float) -> str:
    return f"[{lo:+.3f}, {hi:+.3f}]"


def _write(name: str, body: str, sources: list[str]) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(body, encoding="utf-8")
    MANIFEST[name] = sources
    print(f"wrote {name}  <- {sources}")


def tab_main() -> None:
    """FINAL-protocol aggregate: mean+-std over 30 scenarios (10 seeds x 3 rates).

    FINE/Co-Teaching are EXCLUDED: results/p7_baseline_expansion.csv ran under the
    legacy P2d stratified audit window (sample_policy field), not the frozen
    masked+group-disjoint FINAL protocol -- cross-protocol rows would be a false
    comparison (see tab_baselines_iid.tex).
    """
    p5 = pd.read_csv("results/p5_factor_ablation_full.csv")
    p4 = pd.read_csv("results/p4_cl_graph_combo_full_family_b_complete.csv")
    cell_names = {
        "4_graph_cdm_soft": "Graph-CoLD-soft",
        "3_graph_cdm_hard": "Hard deletion (ablation)",
        "5_graph_cdm_freqfloor": "Freq-floor reweighting",
        "6_nograph_cbce": "Class-balanced CE (no graph)",
    }
    rows = []
    for ds in DS_ORDER:
        for cell, label in cell_names.items():
            g = p5[(p5.dataset == ds) & (p5.cell == cell)]
            rows.append((ds, label, g.macro_f1, g.tail_macro_f1))
        for m, label in [("Confident-Learning", "Confident Learning"), ("CL+Graph-soft", "CL + Graph-CDM soft")]:
            g = p4[(p4.dataset == ds) & (p4.method == m)]
            rows.append((ds, label, g.macro_f1, g.tail_macro_f1))
    lines = [
        "% AUTO-GENERATED by src/paper/w5_result_tables.py -- do not hand-edit numbers",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Final frozen protocol (proxy-masked features, group-disjoint primary splits):",
        " mean$\\pm$std over 10 seeds $\\times$ asymmetric tail-noise rates \\{0.4, 0.6, 0.8\\}.",
        " The historical CoLD-aligned proxy is not part of this grid (Section~\\ref{sec:cold-fidelity}).}",
        "\\label{tab:main}", "\\small",
        "\\begin{tabular}{llcc}", "\\toprule",
        "Dataset & Method & Macro-F1 & Tail-F1 \\\\", "\\midrule",
    ]
    prev = None
    for ds, label, mac, tail in rows:
        d = DS_LABEL[ds] if ds != prev else ""
        if ds != prev and prev is not None:
            lines.append("\\midrule")
        prev = ds
        assert len(mac) == 30, f"{ds}/{label}: expected 30 rows, got {len(mac)}"
        lines.append(
            f"{d} & {label} & {mac.mean():.3f}$\\pm${mac.std(ddof=1):.3f} & "
            f"{tail.mean():.3f}$\\pm${tail.std(ddof=1):.3f} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    _write("tab_main.tex", "\n".join(lines) + "\n",
           ["results/p5_factor_ablation_full.csv", "results/p4_cl_graph_combo_full_family_b_complete.csv"])


