def tab_leakage() -> None:
    lk = pd.read_csv("tables/table_p6_leakage_ablation_fixedtail_all.csv")
    tail = lk[lk.metric == "tail_f1"]

    def cell(ds: str, method: str, cond: str) -> str:
        g = tail[(tail.dataset == ds) & (tail.method == method) & (tail.condition == cond)]
        if g.empty:
            return "n/a"
        r = g.iloc[0]
        star = "" if r.bootstrap_ci95_low <= 0 <= r.bootstrap_ci95_high else "$^{*}$"
        return f"{r.mean_delta:+.3f}{star}"

    conds = ["DUP", "ENT", "PRX", "ORA", "ALL"]
    methods = [("CoLD", "CoLD-aligned proxy"), ("ablation_hard", "Hard deletion"), ("Graph-CoLD-soft", "Soft retention")]
    lines = [
        "% AUTO-GENERATED by src/paper/w5_result_tables.py",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Four-factor leakage decomposition (descriptive, 10 seeds, rate 0.6):",
        " Tail-F1 $\\Delta$ of each leakage condition vs.\\ the final frozen protocol.",
        " $^{*}$: bootstrap 95\\% CI excludes zero. CICIDS ENT is infeasible by construction",
        " (giant connected component; Section~\\ref{sec:limitations}). Leakage flatters",
        " deletion-style methods most and compresses the apparent soft-retention advantage.}",
        "\\label{tab:leakage}", "\\small",
        "\\begin{tabular}{llccccc}", "\\toprule",
        "Dataset & Method & DUP & ENT & PRX & ORA & ALL \\\\", "\\midrule",
    ]
    prev = None
    for ds in DS_ORDER:
        for m, label in methods:
            d = DS_LABEL[ds] if ds != prev else ""
            if ds != prev and prev is not None:
                lines.append("\\midrule")
            prev = ds
            cells = " & ".join(cell(ds, m, c) for c in conds)
            lines.append(f"{d} & {label} & {cells} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    _write("tab_leakage.tex", "\n".join(lines) + "\n",
           ["tables/table_p6_leakage_ablation_fixedtail_all.csv"])


def tab_natural_noise() -> None:
    nn = json.load(open("reports/p7_natural_noise.json"))
    means = nn["per_method_means"]
    deltas = {d["pair"]: d for d in nn["deltas_cleanref"] if d["metric"] == "tail_f1_cleanref"}
    order = [("Graph-CoLD-soft", "Graph-CoLD-soft"), ("Confident-Learning", "Confident Learning"),
             ("ablation_hard", "Hard deletion"), ("CoLD", "CoLD-aligned proxy")]
    lines = [
        "% AUTO-GENERATED by src/paper/w5_result_tables.py",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Real labelling errors (CICIDS-2017, Engelen-corrected reference; descriptive,",
        " 10 seeds, frozen temporal window). Training uses the original released labels",
        " (4.7\\% real train-pool errors); evaluation uses corrected labels. The soft-vs-hard",
        " direction holds under real noise: $\\Delta$ Tail-F1 $+0.284$ $[+0.089, +0.487]$.}",
        "\\label{tab:natural-noise}", "\\small",
        "\\begin{tabular}{lcc}", "\\toprule",
        "Method & Macro-F1 & Tail-F1 \\\\", "\\midrule",
    ]
    for key, label in order:
        m = means[key]
        lines.append(f"{label} & {m['macro_f1_cleanref']:.3f} & {m['tail_f1_cleanref']:.3f} \\\\")
    d = deltas["Graph-CoLD-soft-ablation_hard"]
    lines += [
        "\\midrule",
        f"\\multicolumn{{3}}{{l}}{{Soft $-$ hard, Tail-F1: {d['mean_delta']:+.3f} "
        f"{_ci(d['bootstrap_ci95_low'], d['bootstrap_ci95_high'])} (paired, $n{{=}}10$)}} \\\\",
        "\\bottomrule", "\\end{tabular}", "\\end{table}",
    ]
    _write("tab_natural_noise.tex", "\n".join(lines) + "\n", ["reports/p7_natural_noise.json"])


def main() -> None:
    tab_main()
    tab_baselines_iid()
    tab_family_a()
    tab_family_b()
    tab_family_c()
    tab_leakage()
    tab_natural_noise()
    (OUT / "traceability_manifest.json").write_text(json.dumps(MANIFEST, indent=2), encoding="utf-8")
    print("manifest written;", len(MANIFEST), "tables")


if __name__ == "__main__":
    main()
